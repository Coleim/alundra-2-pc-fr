#!/usr/bin/env python3
"""Build the symbol file splat reads for the main executable.

Layers, later ones win:
  1. automatic names  func_XXXXXXXX  for every recompiler seed (seeds/ghidra_funcs.txt)
  2. BIOS thunk names                (symbols/bios_thunks.txt, from tools/name_bios_stubs.py)
     library names from debug strings (symbols/lib_names.txt, from tools/name_by_strings.py)
     PsyQ library names by signature  (symbols/psyq_names.txt, from tools/psyq_sigs.py)
  3. hand-made names and types       (symbols/manual.txt)
A name used at two addresses keeps the later layer's address; the other gets an _XXXXXXXX suffix.
"""
import re
import sys

SYM = re.compile(r"^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(0x[0-9A-Fa-f]+)\s*;(.*)$")


def read_layer(path):
    out = {}
    try:
        for line in open(path):
            m = SYM.match(line)
            if m:
                out[int(m.group(2), 16)] = (m.group(1), m.group(3).strip())
    except FileNotFoundError:
        pass
    return out


def main():
    syms = {}
    for line in open("seeds/ghidra_funcs.txt"):
        line = line.strip()
        if line and not line.startswith("#"):
            a = int(line, 16)
            syms[a] = (f"func_{a:08X}", "// type:func")
    owner = {}                                   # name -> address, later layers win
    for layer in ("symbols/bios_thunks.txt", "symbols/lib_names.txt", "symbols/psyq_names.txt",
                  "symbols/manual.txt"):
        for a, (n, rest) in read_layer(layer).items():
            syms[a] = (n, rest)
            owner[n] = a
    for a, (n, rest) in list(syms.items()):
        if owner.get(n, a) != a:
            print(f"warning: {n} also at {owner[n]:#010x}; {a:#010x} renamed {n}_{a:08X}", file=sys.stderr)
            syms[a] = (f"{n}_{a:08X}", rest)
    with open("symbols/main_symbols.txt", "w") as f:
        f.write("// Generated by tools/build_symbols.py - edit symbols/manual.txt instead.\n")
        for a in sorted(syms):
            n, rest = syms[a]
            f.write(f"{n} = 0x{a:08X}; {rest}\n")
    print(f"{len(syms)} symbols -> symbols/main_symbols.txt")


if __name__ == "__main__":
    sys.exit(main())
